export type SupportStatus = 'Supported' | 'Security fixes only' | 'End of life';

export function supportStatus(v: UmbracoVersion, on: Date = new Date()): SupportStatus {
  const day = on.toISOString().slice(0, 10);
  if (day >= v.endOfLife) return 'End of life';
  if (day >= v.securityPhase) return 'Security fixes only';
  return 'Supported';
}

export function formatDate(iso: string): string {
  return new Date(`${iso}T00:00:00Z`).toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  });
}
